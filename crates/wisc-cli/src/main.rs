use std::{
    fs,
    path::{Path, PathBuf},
};

use anyhow::{Context, Result};
use clap::{Parser, Subcommand, ValueEnum};
use rustplotlib::{Axes, Figure, IntendedUse, Layer, Line, MarkerShape, MarkerStyle};
use serde::Deserialize;
use wisc_core::imaging::{decode, FitsByteOrder};
use wisc_core::workflow::{automatic_fit_preserving, visible_catalog, CalibrationDocument, FitJob};
use wisc_core::{detect_stars, DetectorConfig, FitResult};

#[derive(Debug, Parser)]
#[command(name = "wisc", version, about = "WISC wide-field star calibration")]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Clone, Copy, Debug, ValueEnum)]
enum ByteOrder {
    Auto,
    Big,
    Little,
}

impl From<ByteOrder> for FitsByteOrder {
    fn from(value: ByteOrder) -> Self {
        match value {
            ByteOrder::Auto => Self::Auto,
            ByteOrder::Big => Self::Big,
            ByteOrder::Little => Self::Little,
        }
    }
}

#[derive(Debug, Subcommand)]
enum Command {
    /// Generate a complete local report, preserving the original image.
    Report {
        input: PathBuf,
        #[arg(long)]
        image: PathBuf,
        #[arg(short, long, default_value = "wisc-calibration-report.zip")]
        output: PathBuf,
    },
    /// Export equidistant/equisolid MIRACLE compatibility approximations.
    Miracle {
        input: PathBuf,
        #[arg(long)]
        ascii: bool,
        #[arg(short, long)]
        output: Option<PathBuf>,
    },
    /// Export a self-contained mapper or full-precision parameter declaration.
    Export {
        calibration: PathBuf,
        #[arg(long,default_value="python",value_parser=["python","julia","matlab","c"])]
        language: String,
        #[arg(long)]
        parameters_only: bool,
        #[arg(short, long)]
        output: Option<PathBuf>,
    },
    /// Measure a star with the same 40× KDE picker used by the Rust browser.
    Centroid {
        image: PathBuf,
        /// Raw zero-based image pixel centre.
        #[arg(long, allow_hyphen_values = true)]
        x: f64,
        #[arg(long, allow_hyphen_values = true)]
        y: f64,
        #[arg(long, value_enum, default_value = "auto")]
        fits_byte_order: ByteOrder,
        #[arg(short, long, default_value = "centroid.json")]
        output: PathBuf,
    },
    /// Export azimuth/elevation as FITS planes or an HDF5 pixel-corner grid.
    Map {
        calibration: PathBuf,
        #[arg(short, long, default_value = "azel.fits")]
        output: PathBuf,
        /// Sampling step in raw image pixels (1 writes every pixel centre).
        #[arg(long,default_value_t=1,value_parser=clap::value_parser!(u32).range(1..))]
        step: u32,
    },
    /// Detect, associate catalogue stars, and fit from a roughly aligned model.
    Solve {
        image: PathBuf,
        /// Byte order for 16-bit FITS data; auto uses the legacy smoothness test.
        #[arg(long, value_enum, default_value = "auto")]
        fits_byte_order: ByteOrder,
        /// Saved test case or fit job with initial model, site, and UTC time.
        #[arg(long)]
        initial: PathBuf,
        #[arg(short, long, default_value = "calibration.json")]
        output: PathBuf,
        #[arg(long, default_value_t = 12.0)]
        match_radius: f64,
        #[arg(long, default_value_t = 5.0)]
        max_magnitude: f64,
        #[arg(long,default_value="tycho2",value_parser=["tycho2","yale","td1"])]
        catalogue: String,
        #[arg(long, default_value_t = 2000)]
        max_iterations: usize,
        #[arg(long)]
        residual_plot: Option<PathBuf>,
        /// Recover pointing with triangles; approximate lens intrinsics required.
        #[arg(long)]
        triangles: bool,
    },
    /// Detect stellar point sources in a PNG, JPEG, HEIC/HEIF, or FITS image.
    Detect {
        image: PathBuf,
        /// Explicit override for nonstandard 16-bit FITS files.
        #[arg(long, value_enum, default_value = "auto")]
        fits_byte_order: ByteOrder,
        /// Machine-readable detection list.
        #[arg(short, long, default_value = "detections.json")]
        output: PathBuf,
        #[arg(long, default_value_t = 5.0)]
        threshold_sigma: f64,
        #[arg(long, default_value_t = 500)]
        max_stars: usize,
    },
    /// Fit a camera model to identified sky/image star pairs.
    Fit {
        /// JSON or WISC HDF5 containing a calibration and identified pairs.
        input: PathBuf,
        /// Machine-readable fitted calibration and residual summary.
        #[arg(short, long, default_value = "calibration.json")]
        output: PathBuf,
        /// Optional PDF, SVG, PNG or JPEG residual plot generated by rustplotlib.
        #[arg(long)]
        residual_plot: Option<PathBuf>,
        #[arg(long, default_value_t = 2000)]
        max_iterations: usize,
        /// Use Levenberg–Marquardt instead of Nelder–Mead.
        #[arg(long)]
        lm: bool,
        /// Keep these zero-based optpar indices unchanged, e.g. 8,9,10,11.
        #[arg(long, value_delimiter = ',')]
        fixed: Vec<usize>,
    },
    /// Project azimuth/zenith samples through an existing calibration.
    Project {
        calibration: PathBuf,
        /// JSON array of objects with azimuth_rad and zenith_rad.
        samples: PathBuf,
    },
}

#[derive(Debug, Deserialize)]
struct SkyPosition {
    azimuth_rad: f64,
    zenith_rad: f64,
}

fn read_json<T: for<'de> Deserialize<'de>>(path: &Path) -> Result<T> {
    serde_json::from_slice(&fs::read(path).with_context(|| format!("reading {}", path.display()))?)
        .with_context(|| format!("parsing {}", path.display()))
}

fn read_job(path: &Path) -> Result<FitJob> {
    wisc_core::products::import_job(&fs::read(path)?)
        .map_err(anyhow::Error::msg)
        .with_context(|| format!("importing {}", path.display()))
}

fn is_hdf5(path: &Path) -> bool {
    path.extension()
        .and_then(|s| s.to_str())
        .is_some_and(|s| s.eq_ignore_ascii_case("h5") || s.eq_ignore_ascii_case("hdf5"))
}

fn save_fit(
    output: &Path,
    plot: Option<&Path>,
    result: &FitResult,
    job: &FitJob,
    source: &Path,
) -> Result<()> {
    let document = CalibrationDocument::from_fit(result, job).map_err(anyhow::Error::msg)?;
    let mut session =
        wisc_core::products::read_session(&fs::read(source)?).map_err(anyhow::Error::msg)?;
    let metadata =
        wisc_core::products::source_metadata(&fs::read(source)?).map_err(anyhow::Error::msg)?;
    if let Some(session) = &mut session {
        session.job = job.clone();
        session.job.initial = result.calibration.clone();
    }
    if let Some(path) = plot {
        residual_plot(path, &document.residuals_px, result.rms_px)
            .with_context(|| format!("writing residual plot {}", path.display()))?;
    }
    let bytes = if is_hdf5(output) {
        if let Some(session) = &session {
            wisc_core::products::session_hdf5(session, Some(result)).map_err(anyhow::Error::msg)?
        } else {
            wisc_core::products::calibration_with_metadata_hdf5(job, Some(result), &metadata)
                .map_err(anyhow::Error::msg)?
        }
    } else {
        let mut value = serde_json::to_value(&document)?;
        if let Some(session) = session {
            value["session"] = serde_json::to_value(session)?;
        } else {
            value["source_metadata"] = metadata;
        }
        serde_json::to_vec_pretty(&value)?
    };
    fs::write(output, bytes)?;
    println!(
        "{}: {} pairs, RMS {:.4} px",
        output.display(),
        job.pairs.len(),
        document.rms_px
    );
    Ok(())
}

fn residual_plot(path: &Path, residuals: &[[f64; 2]], rms: f64) -> Result<()> {
    let extent = residuals
        .iter()
        .flat_map(|point| point.iter())
        .map(|value| value.abs())
        .fold(1.0_f64, f64::max)
        .max(rms * 2.0)
        * 1.1;
    let mut figure = Figure::new(IntendedUse::ArticleColumn);
    let panels = figure.grid(1, 1)?;
    let panel_index = panels[0];
    let panel = &mut figure.panels[panel_index];
    panel.axes = Some(Axes::new(
        [-extent, extent],
        [-extent, extent],
        r"$\Delta x\;[\mathrm{pixel}]$",
        r"$\Delta y\;[\mathrm{pixel}]$",
    ));
    panel.push(Layer::Line(Line::new(
        vec![[-extent, 0.0], [extent, 0.0]],
        "#9aa3aa",
    )));
    panel.push(Layer::Line(Line::new(
        vec![[0.0, -extent], [0.0, extent]],
        "#9aa3aa",
    )));
    let mut panel = figure.panels.remove(panel_index);
    panel.markers(
        &mut figure,
        residuals,
        &MarkerStyle {
            shape: MarkerShape::Circle,
            size_pt: 4.5,
            color: [0.12, 0.36, 0.58],
        },
    )?;
    figure.panels.insert(panel_index, panel);
    figure.save(path)?;
    Ok(())
}

fn overlay_plot(path: &Path, bytes: &[u8], session: &wisc_core::session::Session) -> Result<()> {
    let job = &session.job;
    let order = match session
        .display
        .get("fitsByteOrder")
        .and_then(serde_json::Value::as_str)
    {
        Some("big") => FitsByteOrder::Big,
        Some("little") => FitsByteOrder::Little,
        _ => FitsByteOrder::Auto,
    };
    let decoded = decode(bytes, order).map_err(anyhow::Error::msg)?;
    anyhow::ensure!(
        (decoded.width, decoded.height) == (job.initial.width, job.initial.height),
        "overlay image dimensions differ from calibration"
    );
    let image = image::RgbaImage::from_raw(decoded.width, decoded.height, decoded.rgba)
        .context("invalid image pixels")?;
    let mut figure = Figure::new(IntendedUse::ArticleColumn);
    figure.height_mm =
        figure.width_mm * job.initial.height as f64 / job.initial.width as f64 + 18.0;
    figure.raster_dpi = 300.0;
    let panel = figure.grid(1, 1)?[0];
    figure.panels[panel].axes = Some(Axes::new(
        [-0.5, job.initial.width as f64 - 0.5],
        [-(job.initial.height as f64) + 0.5, 0.5],
        "x [pixel]",
        "-y [pixel]",
    ));
    figure.panels[panel].push(Layer::Image(image));
    let measured: Vec<_> = job.pairs.iter().map(|p| [p.x_px, -p.y_px]).collect();
    let predicted: Vec<_> = job
        .pairs
        .iter()
        .filter_map(|p| job.initial.project(p.azimuth_rad, p.zenith_rad))
        .map(|p| [p[0], -p[1]])
        .collect();
    let mut panel = figure.panels.remove(panel);
    panel.markers(
        &mut figure,
        &measured,
        &MarkerStyle {
            shape: MarkerShape::Circle,
            size_pt: 3.5,
            color: [0.1, 0.8, 0.9],
        },
    )?;
    panel.markers(
        &mut figure,
        &predicted,
        &MarkerStyle {
            shape: MarkerShape::Circle,
            size_pt: 2.0,
            color: [1.0, 0.5, 0.1],
        },
    )?;
    figure.panels.push(panel);
    figure.save(path)?;
    Ok(())
}

fn run() -> Result<()> {
    match Cli::parse().command {
        Command::Report {
            input,
            image,
            output,
        } => {
            let source = fs::read(&input)?;
            let job = read_job(&input)?;
            let bytes = fs::read(&image)?;
            let session = if let Some(session) =
                wisc_core::products::read_session(&source).map_err(anyhow::Error::msg)?
            {
                session
            } else {
                wisc_core::session::Session {
                    schema: wisc_core::session::SCHEMA.into(),
                    image_sha256: wisc_core::session::image_digest(&bytes),
                    image_name: image
                        .file_name()
                        .and_then(|s| s.to_str())
                        .unwrap_or("image")
                        .into(),
                    job: job.clone(),
                    metadata: wisc_core::products::source_metadata(&source)
                        .map_err(anyhow::Error::msg)?,
                    display: serde_json::Value::Null,
                    masked_tiles: vec![],
                }
            };
            session
                .verify_image(&bytes, job.initial.width, job.initial.height)
                .map_err(anyhow::Error::msg)?;
            let directory = tempfile::tempdir()?;
            let residuals: Vec<_> = job
                .pairs
                .iter()
                .map(|p| {
                    job.initial
                        .project(p.azimuth_rad, p.zenith_rad)
                        .map(|q| [q[0] - p.x_px, q[1] - p.y_px])
                        .context("invalid selected-star projection")
                })
                .collect::<Result<_>>()?;
            let rms = (residuals
                .iter()
                .map(|r| r[0] * r[0] + r[1] * r[1])
                .sum::<f64>()
                / residuals.len().max(1) as f64)
                .sqrt();
            let path = directory.path().join("residuals.png");
            residual_plot(&path, &residuals, rms)?;
            let mut assets = vec![("residuals.png", fs::read(&path)?)];
            let compatibility = wisc_core::miracle::product(&job).map_err(anyhow::Error::msg)?;
            for (name, rows, summary) in [
                (
                    "miracle_equidistant.png",
                    &compatibility.equidistant_residuals,
                    &compatibility.equidistant_summary,
                ),
                (
                    "miracle_equisolid.png",
                    &compatibility.equisolid_residuals,
                    &compatibility.equisolid_summary,
                ),
            ] {
                let path = directory.path().join(name);
                let xy: Vec<_> = rows.iter().map(|r| [r[1], r[0]]).collect();
                residual_plot(&path, &xy, summary.rms_pixel.unwrap_or(0.0))?;
                assets.push((name, fs::read(path)?));
            }
            let overlay = directory.path().join("overlay.png");
            overlay_plot(&overlay, &bytes, &session)?;
            assets.push(("overlay.png", fs::read(overlay)?));
            let archive =
                wisc_core::report::bundle(&session, &bytes, &assets).map_err(anyhow::Error::msg)?;
            fs::write(&output, archive)?;
            println!(
                "{}: complete Rust report, {} stars, RMS {:.6} px",
                output.display(),
                job.pairs.len(),
                rms
            );
        }
        Command::Miracle {
            input,
            ascii,
            output,
        } => {
            let product =
                wisc_core::miracle::product(&read_job(&input)?).map_err(anyhow::Error::msg)?;
            let text = if ascii {
                wisc_core::miracle::ascii(&product)
            } else {
                serde_json::to_string_pretty(&product)?
            };
            if let Some(path) = output {
                fs::write(path, text)?;
            } else {
                println!("{text}");
            }
        }
        Command::Export {
            calibration,
            language,
            parameters_only,
            output,
        } => {
            let job = read_job(&calibration)?;
            let text = if parameters_only {
                wisc_core::code_exports::parameters(&job.initial, &language)
            } else {
                wisc_core::code_exports::mapper(&job.initial, &language)
            }
            .map_err(anyhow::Error::msg)?;
            if let Some(path) = output {
                fs::write(path, text)?;
            } else {
                println!("{text}");
            }
        }
        Command::Centroid {
            image,
            x,
            y,
            fits_byte_order,
            output,
        } => {
            let image =
                decode(&fs::read(image)?, fits_byte_order.into()).map_err(anyhow::Error::msg)?;
            let centroid = wisc_core::inspection::kde_centroid(
                &image.luminance,
                image.width as usize,
                image.height as usize,
                [x, y],
            )
            .map_err(anyhow::Error::msg)?;
            let result = serde_json::json!({"x_px":centroid.position[0],"y_px":centroid.position[1],"background":centroid.background,"method":"40x upsampled KDE","sigma_px":53.2/40.0});
            fs::write(output, serde_json::to_vec_pretty(&result)?)?;
        }
        Command::Map {
            calibration,
            output,
            step,
        } => {
            let job = read_job(&calibration)?;
            if is_hdf5(&output) {
                anyhow::ensure!(
                    step == 1,
                    "HDF5 maps use the full pixel-corner grid; --step must be 1"
                );
                let bytes = wisc_core::products::azel_hdf5(&job.initial, job.observation.as_ref())
                    .map_err(anyhow::Error::msg)?;
                fs::write(&output, bytes)?;
            } else {
                let mut writer = std::io::BufWriter::new(fs::File::create(&output)?);
                wisc_core::imaging::write_azel_fits(&mut writer, &job.initial, step)
                    .map_err(anyhow::Error::msg)?;
                std::io::Write::flush(&mut writer)?;
            }
            println!(
                "{}: azimuth/elevation in degrees, step {} px",
                output.display(),
                step
            );
        }
        Command::Solve {
            image,
            fits_byte_order,
            initial,
            output,
            match_radius,
            max_magnitude,
            catalogue,
            max_iterations,
            residual_plot,
            triangles,
        } => {
            let mut job = read_job(&initial)?;
            let observation = job
                .observation
                .as_ref()
                .context("automatic association needs observation time and site")?;
            let decoded =
                decode(&fs::read(&image)?, fits_byte_order.into()).map_err(anyhow::Error::msg)?;
            anyhow::ensure!(
                decoded.width == job.initial.width && decoded.height == job.initial.height,
                "image dimensions differ from the initial calibration"
            );
            let detections = detect_stars(
                &decoded.luminance,
                decoded.width,
                decoded.height,
                DetectorConfig::default(),
            );
            let catalogue: Vec<_> = wisc_core::catalogues::load(&catalogue)
                .map_err(anyhow::Error::msg)?
                .into_iter()
                .map(|entry| entry.star)
                .collect();
            let sky = visible_catalog(&catalogue, observation, max_magnitude)
                .map_err(anyhow::Error::msg)?;
            let matcher = if triangles {
                wisc_core::asterism::triangle_fit
            } else {
                automatic_fit_preserving
            };
            let (result, pairs) = matcher(
                &job.initial,
                &detections,
                &sky,
                &job.pairs,
                match_radius,
                max_iterations,
            )
            .map_err(anyhow::Error::msg)?;
            job.pairs = pairs;
            save_fit(&output, residual_plot.as_deref(), &result, &job, &initial)?;
        }
        Command::Detect {
            image,
            fits_byte_order,
            output,
            threshold_sigma,
            max_stars,
        } => {
            let decoded = decode(&fs::read(&image)?, fits_byte_order.into())
                .map_err(anyhow::Error::msg)
                .with_context(|| format!("decoding {}", image.display()))?;
            let detections = detect_stars(
                &decoded.luminance,
                decoded.width,
                decoded.height,
                DetectorConfig {
                    threshold_sigma,
                    max_stars,
                    ..DetectorConfig::default()
                },
            );
            fs::write(&output, serde_json::to_vec_pretty(&detections)?)
                .with_context(|| format!("writing {}", output.display()))?;
            println!(
                "{}: {} detections in {} × {} image",
                output.display(),
                detections.len(),
                decoded.width,
                decoded.height
            );
        }
        Command::Fit {
            input,
            output,
            residual_plot: plot,
            max_iterations,
            lm,
            fixed,
        } => {
            let job = read_job(&input)?;
            let active =
                wisc_core::active_parameters(&job.initial, &fixed).map_err(anyhow::Error::msg)?;
            let solver = if lm {
                wisc_core::optimization::fit_lm_with_active
            } else {
                wisc_core::fit_with_active
            };
            let result = solver(&job.initial, &job.pairs, max_iterations, &active)
                .map_err(anyhow::Error::msg)?;
            save_fit(&output, plot.as_deref(), &result, &job, &input)?;
        }
        Command::Project {
            calibration,
            samples,
        } => {
            let calibration = read_job(&calibration)?.initial;
            calibration.validate().map_err(anyhow::Error::msg)?;
            let samples: Vec<SkyPosition> = read_json(&samples)?;
            let projected: Vec<Option<[f64; 2]>> = samples
                .iter()
                .map(|sample| calibration.project(sample.azimuth_rad, sample.zenith_rad))
                .collect();
            println!("{}", serde_json::to_string_pretty(&projected)?);
        }
    }
    Ok(())
}

fn main() {
    if let Err(error) = run() {
        eprintln!("wisc: {error:#}");
        std::process::exit(1);
    }
}

