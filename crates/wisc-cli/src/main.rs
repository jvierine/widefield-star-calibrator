use std::{
    fs,
    path::{Path, PathBuf},
};

use anyhow::{Context, Result};
use clap::{Parser, Subcommand};
use rustplotlib::{Axes, Figure, IntendedUse, Layer, Line, MarkerShape, MarkerStyle};
use serde::{Deserialize, Serialize};
use wisc_core::{detect_stars, fit, Calibration, DetectorConfig, FitResult, StarPair};

#[derive(Debug, Parser)]
#[command(name = "wisc", version, about = "WISC wide-field star calibration")]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Debug, Subcommand)]
enum Command {
    /// Detect stellar point sources in a PNG or JPEG image.
    Detect {
        image: PathBuf,
        /// Machine-readable detection list.
        #[arg(short, long, default_value = "detections.json")]
        output: PathBuf,
        #[arg(long, default_value_t = 5.0)]
        threshold_sigma: f64,
        #[arg(long, default_value_t = 500)]
        max_stars: usize,
    },
    /// Fit a camera model to identified sky/image star pairs.
    Fit {
        /// JSON job containing an initial calibration and identified pairs.
        input: PathBuf,
        /// Machine-readable fitted calibration and residual summary.
        #[arg(short, long, default_value = "calibration.json")]
        output: PathBuf,
        /// Optional PDF, SVG, PNG or JPEG residual plot generated by rustplotlib.
        #[arg(long)]
        residual_plot: Option<PathBuf>,
        #[arg(long, default_value_t = 2000)]
        max_iterations: usize,
    },
    /// Project azimuth/zenith samples through an existing calibration.
    Project {
        calibration: PathBuf,
        /// JSON array of objects with azimuth_rad and zenith_rad.
        samples: PathBuf,
    },
}

#[derive(Debug, Deserialize)]
struct FitJob {
    initial: Calibration,
    pairs: Vec<StarPair>,
}

#[derive(Debug, Serialize)]
struct FitOutput {
    schema: &'static str,
    solved: bool,
    rms_px: f64,
    iterations: usize,
    calibration: Calibration,
    residuals_px: Vec<[f64; 2]>,
}

#[derive(Debug, Deserialize)]
struct SkyPosition {
    azimuth_rad: f64,
    zenith_rad: f64,
}

fn read_json<T: for<'de> Deserialize<'de>>(path: &Path) -> Result<T> {
    serde_json::from_slice(&fs::read(path).with_context(|| format!("reading {}", path.display()))?)
        .with_context(|| format!("parsing {}", path.display()))
}

fn residuals(result: &FitResult, pairs: &[StarPair]) -> Result<Vec<[f64; 2]>> {
    pairs
        .iter()
        .map(|pair| {
            result
                .calibration
                .project(pair.azimuth_rad, pair.zenith_rad)
                .map(|pixel| [pixel[0] - pair.x_px, pixel[1] - pair.y_px])
                .context("fitted model produced a non-finite projection")
        })
        .collect()
}

fn residual_plot(path: &Path, residuals: &[[f64; 2]], rms: f64) -> Result<()> {
    let extent = residuals
        .iter()
        .flat_map(|point| point.iter())
        .map(|value| value.abs())
        .fold(1.0_f64, f64::max)
        .max(rms * 2.0)
        * 1.1;
    let mut figure = Figure::new(IntendedUse::ArticleColumn);
    let panels = figure.grid(1, 1)?;
    let panel_index = panels[0];
    let panel = &mut figure.panels[panel_index];
    panel.axes = Some(Axes::new(
        [-extent, extent],
        [-extent, extent],
        r"$\Delta x\;[\mathrm{pixel}]$",
        r"$\Delta y\;[\mathrm{pixel}]$",
    ));
    panel.push(Layer::Line(Line::new(
        vec![[-extent, 0.0], [extent, 0.0]],
        "#9aa3aa",
    )));
    panel.push(Layer::Line(Line::new(
        vec![[0.0, -extent], [0.0, extent]],
        "#9aa3aa",
    )));
    let mut panel = figure.panels.remove(panel_index);
    panel.markers(
        &mut figure,
        residuals,
        &MarkerStyle {
            shape: MarkerShape::Circle,
            size_pt: 4.5,
            color: [0.12, 0.36, 0.58],
        },
    )?;
    figure.panels.insert(panel_index, panel);
    figure.save(path)?;
    Ok(())
}

fn run() -> Result<()> {
    match Cli::parse().command {
        Command::Detect {
            image,
            output,
            threshold_sigma,
            max_stars,
        } => {
            let decoded = image::ImageReader::open(&image)
                .with_context(|| format!("opening {}", image.display()))?
                .with_guessed_format()
                .context("identifying image format")?
                .decode()
                .with_context(|| format!("decoding {}", image.display()))?
                .to_rgba8();
            let luminance: Vec<f32> = decoded
                .pixels()
                .map(|pixel| {
                    0.2126 * f32::from(pixel[0])
                        + 0.7152 * f32::from(pixel[1])
                        + 0.0722 * f32::from(pixel[2])
                })
                .collect();
            let detections = detect_stars(
                &luminance,
                decoded.width(),
                decoded.height(),
                DetectorConfig {
                    threshold_sigma,
                    max_stars,
                    ..DetectorConfig::default()
                },
            );
            fs::write(&output, serde_json::to_vec_pretty(&detections)?)
                .with_context(|| format!("writing {}", output.display()))?;
            println!(
                "{}: {} detections in {} × {} image",
                output.display(),
                detections.len(),
                decoded.width(),
                decoded.height()
            );
        }
        Command::Fit {
            input,
            output,
            residual_plot: plot,
            max_iterations,
        } => {
            let job: FitJob = read_json(&input)?;
            let result =
                fit(&job.initial, &job.pairs, max_iterations).map_err(anyhow::Error::msg)?;
            let residuals = residuals(&result, &job.pairs)?;
            if let Some(path) = plot {
                residual_plot(&path, &residuals, result.rms_px).with_context(|| {
                    format!("writing rustplotlib residual plot {}", path.display())
                })?;
            }
            let document = FitOutput {
                schema: "wisc.calibration/v1",
                solved: true,
                rms_px: result.rms_px,
                iterations: result.iterations,
                calibration: result.calibration,
                residuals_px: residuals,
            };
            fs::write(&output, serde_json::to_vec_pretty(&document)?)
                .with_context(|| format!("writing {}", output.display()))?;
            println!("{}: RMS {:.4} px", output.display(), document.rms_px);
        }
        Command::Project {
            calibration,
            samples,
        } => {
            let calibration: Calibration = read_json(&calibration)?;
            calibration.validate().map_err(anyhow::Error::msg)?;
            let samples: Vec<SkyPosition> = read_json(&samples)?;
            let projected: Vec<Option<[f64; 2]>> = samples
                .iter()
                .map(|sample| calibration.project(sample.azimuth_rad, sample.zenith_rad))
                .collect();
            println!("{}", serde_json::to_string_pretty(&projected)?);
        }
    }
    Ok(())
}

fn main() {
    if let Err(error) = run() {
        eprintln!("wisc: {error:#}");
        std::process::exit(1);
    }
}

